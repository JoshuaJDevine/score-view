// Builds web/features/wizard-plugins.js: the instrument plug-ins Bitwig has scanned on this machine (read-only:
// Bitwig's own plug-in metadata cache) plus the user's Bitwig library presets (.bwpreset), for the New Score
// wizard's library palette.
//
//   node tools/scan-plugins.mjs [--out web/features/wizard-plugins.js] [--cache <dir>] [--library <dir>]
//
// Bitwig's cache files (%LOCALAPPDATA%\Bitwig Studio\cache\vst3-metadata-*, clap-metadata-*) are a sequence of
// tagged fields: 00 00 <tag:2> 08 <len:4 BE> <utf-8>. Per plug-in class the fields come in this order:
// 0x3e3 category ("Synth", "Sampler", "Audio FX"...), 0x3e4 name, 0x3e6 vendor, then the id
// (0x3e2 = VST3 class id as 32 hex digits, 0x2ec4 = CLAP id). 0x3ec is the module path.
import fs from 'fs';
import os from 'os';
import path from 'path';
import { fileURLToPath } from 'url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const arg = (k, d) => { const i = process.argv.indexOf(k); return i > 0 ? process.argv[i + 1] : d; };
const CACHE = arg('--cache', path.join(process.env.LOCALAPPDATA || '', 'Bitwig Studio', 'cache'));
const LIBRARY = arg('--library', [path.join(os.homedir(), 'OneDrive', 'Documents', 'Bitwig Studio', 'Library'),
  path.join(os.homedir(), 'Documents', 'Bitwig Studio', 'Library')].find(p => fs.existsSync(p)) || '');
const OUT = arg('--out', path.join(ROOT, 'web/features/wizard-plugins.js'));

const INSTRUMENT_CATS = new Set(['Synth', 'Sampler', 'Drums', 'Instrument', 'Piano', 'Organ']);

export function parseCache(buf, format) {
  const idTag = format === 'clap' ? 0x2ec4 : 0x3e2;
  const out = [];
  let cur = {};
  for (let i = 0; i + 9 < buf.length; i++) {
    if (buf[i] !== 0 || buf[i + 1] !== 0 || buf[i + 4] !== 8) continue;
    const tag = buf[i + 2] * 256 + buf[i + 3];
    const len = buf.readUInt32BE(i + 5);
    if (len <= 0 || len > 1000 || i + 9 + len > buf.length) continue;
    const s = buf.subarray(i + 9, i + 9 + len).toString('utf8');
    if (!/^[^\u0000-\u001f]+$/.test(s)) continue;
    i += 8 + len;
    if (tag === 0x3ec) cur.path = s;
    else if (tag === 0x3e3) cur.category = s;
    else if (tag === 0x3e4) cur.name = s;
    else if (tag === 0x3e6) cur.vendor = s;
    else if (tag === idTag && cur.name) {
      out.push({ format, id: s, name: cur.name, vendor: cur.vendor || '', category: cur.category || '' });
      cur = { path: cur.path };
    }
  }
  return out;
}

function newest(prefix) {
  if (!fs.existsSync(CACHE)) return null;
  const f = fs.readdirSync(CACHE).filter(n => n.startsWith(prefix)).sort().pop();
  return f ? path.join(CACHE, f) : null;
}

function scanPresets(dir) {
  const out = [];
  const walk = d => {
    for (const e of fs.readdirSync(d, { withFileTypes: true })) {
      const p = path.join(d, e.name);
      if (e.isDirectory()) walk(p);
      else if (/\.(bwpreset|vstpreset)$/i.test(e.name)) out.push({ path: p, name: e.name.replace(/\.\w+$/, ''),
        folder: path.basename(path.dirname(p)) });
    }
  };
  if (dir && fs.existsSync(dir)) walk(dir);
  return out;
}

/** One array item per line: small diffs when the inventory changes. */
function serialize(data) {
  const parts = Object.entries(data).map(([k, v]) => '    ' + JSON.stringify(k) + ': ' + (Array.isArray(v)
    ? '[\n' + v.map(x => '      ' + JSON.stringify(x)).join(',\n') + '\n    ]' : JSON.stringify(v)));
  return '{\n' + parts.join(',\n') + '\n  }';
}

function main() {
  const plugins = [];
  const seen = new Set();
  for (const [prefix, format] of [['vst3-metadata', 'vst3'], ['clap-metadata', 'clap']]) {
    const f = newest(prefix);
    if (!f) continue;
    for (const p of parseCache(fs.readFileSync(f), format)) {
      const key = format + ':' + p.id;
      if (seen.has(key) || !INSTRUMENT_CATS.has(p.category)) continue;
      seen.add(key);
      plugins.push(p);
    }
  }
  plugins.sort((a, b) => a.vendor.localeCompare(b.vendor) || a.name.localeCompare(b.name));
  const presets = scanPresets(LIBRARY && path.join(LIBRARY, 'Presets'));
  const noteFx = presets.filter(p => p.folder === 'Note FX Layer');
  const instrumentPresets = presets.filter(p => p.folder !== 'Note FX Layer');
  const data = { generated: new Date().toISOString().slice(0, 10), library: LIBRARY, plugins, noteFx, presets: instrumentPresets };
  const js = '// Generated by tools/scan-plugins.mjs from Bitwig\'s plug-in cache and the user\'s Bitwig library. Re-run to refresh.\n' +
    '// Instrument plug-ins (VST3 class ids / CLAP ids as Bitwig\'s InsertionPoint.insertVST3Device / insertCLAPDevice take them),\n' +
    '// Note FX Layer presets (articulation maps) and instrument presets (.bwpreset) for the New Score wizard palette.\n' +
    '(function (root) {\n  const data = ' + serialize(data) + ';\n' +
    '  if (typeof module !== \'undefined\' && module.exports) module.exports = data;\n' +
    '  else root.SV_WIZARD_PLUGINS = data;\n})(typeof window !== \'undefined\' ? window : this);\n';
  fs.writeFileSync(OUT, js);
  console.log(`${plugins.length} instrument plug-ins, ${noteFx.length} Note FX presets, ${instrumentPresets.length} presets -> ${OUT}`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
