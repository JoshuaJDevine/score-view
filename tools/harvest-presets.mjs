// Harvests instrument presets from DAWproject exports so the New Score wizard can load real patches
// (Bitwig's API can insert a plug-in but cannot pick a patch inside it; a .vstpreset carries the patch).
//
//   node tools/harvest-presets.mjs <export.dawproject> [...more exports]
//
// Writes <Bitwig Studio>/Score View Presets/<plug-in>/<patch>.vstpreset (BBC SO: named by the loaded patch;
// other hosts such as Kontakt/Opus/SINE: named by the track) and regenerates web/features/wizard-presets.js.
import fs from 'fs';
import path from 'path';
import { createRequire } from 'module';
import { fileURLToPath } from 'url';

const require = createRequire(import.meta.url);
const fflate = require('fflate');
const { JSDOM } = await import('jsdom');
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(process.env.USERPROFILE || process.env.HOME, 'OneDrive', 'Documents', 'Bitwig Studio', 'Score View Presets');
const INDEX = path.join(ROOT, 'web', 'features', 'wizard-presets.js');

// BBC SO patch names (longest first so "Tenor Trombones a3" wins over "Tenor Trombone").
const BBC_PATCHES = [
  'Violins 1', 'Violins 2', 'Violas', 'Celli', 'Basses', 'Violin', 'Viola', 'Cello', 'Bass',
  'Piccolo', 'Flutes a3', 'Flute', 'Bass Flute', 'Oboes a3', 'Oboe', 'Cor Anglais', 'Clarinets a3', 'Clarinet',
  'Bass Clarinet', 'Bassoons a3', 'Bassoon', 'Contrabassoon', 'Horns a4', 'Horn', 'Trumpets a3', 'Trumpet',
  'Tenor Trombones a3', 'Tenor Trombone', 'Bass Trombones a2', 'Contrabass Trombone', 'Tuba', 'Contrabass Tuba',
  'Cimbasso', 'Timpani', 'Untuned Percussion', 'Harp', 'Celeste', 'Glockenspiel', 'Crotales', 'Xylophone',
  'Marimba', 'Tubular Bells', 'Vibraphone',
].sort((a, b) => b.length - a.length);

const INSTRUMENT_HOSTS = /BBC Symphony Orchestra|Kontakt|Opus|SINE Player|Spitfire|Abbey Road|Appassionata|Originals|Hammers|Solar|Symphonic Motions|Fractured Strings|Eric Whitacre|Aperture|Fink|BlankFor|Pigments|Serum|Massive|Phase Plant|Piano V|Augmented|UJAM|VD-|VB-|VG-|SE-|BEAUTYFLUTE|Virtual Pianist|Quiet Piano|Love-Fi|Pocket Strings/;
const safe = s => String(s).replace(/[<>:"/\\|?*]+/g, '-').replace(/\s+/g, ' ').trim();

function bbcPatch(buf) {
  const txt = Buffer.from(buf).toString('latin1');
  let best = null;
  for (const name of BBC_PATCHES) {
    const i = txt.indexOf(name);
    if (i >= 0 && (best == null || i < best.i)) best = { name, i };
  }
  return best && best.name;
}

const index = fs.existsSync(INDEX) ? (await import('file://' + INDEX.replace(/\\/g, '/') + '?t=' + Date.now()).catch(() => null)) : null;
const presets = new Map(((index && index.default && index.default.presets) || []).map(p => [p.path, p]));
const files = process.argv.slice(2);
if (!files.length) { console.error('usage: node tools/harvest-presets.mjs <export.dawproject> [...]'); process.exit(2); }

for (const file of files) {
  const zip = fflate.unzipSync(fs.readFileSync(file), { filter: f => f.name === 'project.xml' || /^plugins\//.test(f.name) });
  const doc = new (new JSDOM('').window.DOMParser)().parseFromString(fflate.strFromU8(zip['project.xml']), 'application/xml');
  for (const tr of doc.querySelectorAll('Track')) {
    const track = tr.getAttribute('name') || 'Track';
    for (const dev of tr.querySelectorAll(':scope > Channel > Devices > *')) {
      const plugin = dev.getAttribute('deviceName') || '';
      if (!INSTRUMENT_HOSTS.test(plugin)) continue;
      const statePath = dev.querySelector('State') && dev.querySelector('State').getAttribute('path');
      const bytes = statePath && zip[statePath];
      if (!bytes || !/\.vstpreset$/i.test(statePath)) continue;
      const patch = plugin === 'BBC Symphony Orchestra' ? (bbcPatch(bytes) || track) : track;
      const dir = path.join(OUT, safe(plugin));
      fs.mkdirSync(dir, { recursive: true });
      let name = safe(patch), out = path.join(dir, name + '.vstpreset');
      // Same patch from another track with a different state: keep both.
      if (fs.existsSync(out) && Buffer.compare(fs.readFileSync(out), Buffer.from(bytes)) !== 0 && ![...presets.values()].some(p => p.path === out && p.track === track)) {
        name = safe(patch + ' - ' + track); out = path.join(dir, name + '.vstpreset');
      }
      fs.writeFileSync(out, bytes);
      presets.set(out, { plugin, patch, track, source: path.basename(file), path: out });
      console.log(`${plugin.padEnd(24)} ${patch.padEnd(22)} <- ${track}`);
    }
  }
}

const list = [...presets.values()].sort((a, b) => a.plugin.localeCompare(b.plugin) || a.patch.localeCompare(b.patch));
fs.writeFileSync(INDEX, `// Generated by tools/harvest-presets.mjs — instrument presets harvested from DAWproject exports.
// The New Score wizard loads these instead of an empty plug-in when a row's patch matches.
(function (root) {
  const data = { presets: ${JSON.stringify(list, null, 2).replace(/\n/g, '\n  ')} };
  if (typeof module !== 'undefined' && module.exports) module.exports = data;
  else root.SV_WIZARD_PRESETS = data;
})(typeof window !== 'undefined' ? window : this);
export default undefined;
`.replace('\nexport default undefined;\n', '\n'));
console.log(`\n${list.length} presets indexed in ${path.relative(ROOT, INDEX)}; files in ${OUT}`);
